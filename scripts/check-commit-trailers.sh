#!/usr/bin/env bash
#
# Rejects AI-attribution trailers newly introduced by a commit range.
#
# This check is read-only: it inspects commit messages and never rewrites,
# amends, rebases, or filters history. It scans only the superproject commits in
# the given range; submodule history is never traversed.
#
# Usage:
#   scripts/check-commit-trailers.sh <range>   e.g. origin/main..HEAD
#   scripts/check-commit-trailers.sh --head    check HEAD only
#
# See GIT_GUIDELINES.md for the policy and the CI range/depth rationale.

set -euo pipefail

readonly TRAILER_PATTERN='^[[:space:]]*(co-authored-by|co-authored by|generated-by|generated by|assisted-by|assisted by)[[:space:]]*:'

usage() {
  echo "usage: $0 <git-range> | $0 --head" >&2
  echo "  <git-range>  commits to check, for example origin/main..HEAD" >&2
  echo "  --head       check the current HEAD commit only" >&2
}

if [[ $# -ne 1 ]]; then
  usage
  exit 2
fi

# A shallow checkout cannot resolve a range completely, so a green result would
# be meaningless. Fail with instructions instead of under-reporting.
if [[ "$(git rev-parse --is-shallow-repository)" == "true" ]]; then
  echo "error: this checkout is shallow, so a commit range cannot be checked completely." >&2
  echo "       Fetch full history first: 'git fetch --unshallow'" >&2
  echo "       In CI, check out with 'fetch-depth: 0'." >&2
  exit 2
fi

range="$1"
if [[ "$range" == "--head" ]]; then
  commits="$(git rev-list --max-count=1 HEAD)"
  description="HEAD"
else
  if [[ "$range" != *..* ]]; then
    echo "error: '$range' is not a commit range." >&2
    usage
    exit 2
  fi

  if ! commits="$(git rev-list "$range" 2>/dev/null)"; then
    echo "error: cannot resolve the commit range '$range'." >&2
    echo "       Fetch the missing commits (for example 'git fetch origin') and retry." >&2
    exit 2
  fi

  description="$range"
fi

if [[ -z "$commits" ]]; then
  echo "No commits to check in '$description'."
  exit 0
fi

commit_count=0
failure_count=0

while IFS= read -r commit; do
  [[ -z "$commit" ]] && continue
  commit_count=$((commit_count + 1))

  if matches="$(git log -1 --format=%B "$commit" | grep -inE "$TRAILER_PATTERN")"; then
    subject="$(git log -1 --format=%s "$commit")"
    echo "error: commit $commit introduces an attribution trailer: $subject" >&2
    while IFS= read -r match; do
      echo "       $match" >&2
    done <<< "$matches"
    echo "       Remove the trailer before pushing; see GIT_GUIDELINES.md." >&2
    failure_count=$((failure_count + 1))
  fi
done <<< "$commits"

if [[ "$failure_count" -ne 0 ]]; then
  echo "error: $failure_count of $commit_count commit(s) in '$description' add an attribution trailer." >&2
  exit 1
fi

echo "No attribution trailers in $commit_count commit(s) from '$description'."
